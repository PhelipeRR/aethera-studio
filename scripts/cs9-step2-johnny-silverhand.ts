/**
 * CS-9 Etapa 2: Thumbnail única de Cyberpunk 2077 — Johnny Silverhand
 *
 * Usa o PersistentPythonAiAdapter (worker residente em GPU) para gerar
 * uma única thumbnail com mídia visual fiel e proveniência verificável.
 * Valida com VisualContentGate + CLIP + Quality Gate reais.
 *
 * Prompt ajustado para ≤77 tokens do CLIP/SDXL para evitar truncamento.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';
import sharp from 'sharp';
import {
  AssetIngestionService,
  SharpSvgCompositionEngine,
  QualityGateService,
  evaluateVisualContent,
  ConceptDrivenEngine,
} from '../packages/creative-studio/src/index.js';
import { PersistentPythonAiAdapter } from '../packages/creative-studio/src/persistent-ai-adapter.js';
import type { ReasoningEngineProvider } from '../packages/creative-studio/src/creative-orchestrator.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const OUTPUT_DIR = join(ROOT, 'artifacts', 'cs9-real-generation');

if (!existsSync(OUTPUT_DIR)) mkdirSync(OUTPUT_DIR, { recursive: true });

function mockProvider(): ReasoningEngineProvider {
  return { id: 'claude-code', isAvailable: async () => true, runPrompt: async () => ({ text: 'ok' }) };
}

interface Step2Report {
  concept: string;
  theme: string;
  prompt: string;
  model: string;
  device: string;
  generationTimeSec: number;
  pngPath: string;
  sizeKB: number;
  provenance: string;
  visualGatePassed: boolean;
  visualGateDiagnostics: string[];
  clipScore: number;
  clipMargin: number;
  clipPassed: boolean;
  clipRationale: string;
  qualityScore: number;
  qualityPassed: boolean;
  qualityFindings: string[];
  overallVerdict: 'approved' | 'rejected' | 'failed';
  failureReason?: string;
}

async function main() {
  console.log('=== CS-9 Etapa 2: Johnny Silverhand Thumbnail ===\n');

  const pythonPath = process.env['NB_PYTHON'] ?? 'python';
  const adapter = new PersistentPythonAiAdapter({
    model: 'stabilityai/sdxl-turbo',
    steps: 4,
    timeoutMs: 300_000,
    pythonPath,
  });

  const isAvailable = await adapter.isAvailable();
  if (!isAvailable) {
    console.error('❌ BLOCKED: PersistentPythonAiAdapter not available.');
    process.exit(1);
  }
  console.log('✅ PersistentPythonAiAdapter ready (worker residente em GPU)\n');

  // Prompt ajustado para ≤77 tokens — evita truncamento do CLIP/SDXL
  // Foco em elementos visuais reconhecíveis de Johnny Silverhand sem depender de texto
  const johnnyPrompt =
    'cinematic portrait of silver chrome cybernetic arm with mechanical fingers, ' +
    'aviator sunglasses reflecting neon city lights, cigarette smoke trail, ' +
    'dark moody lighting with pink and blue neon rim light, photorealistic game art';

  const conceptTitle = 'Cyberpunk 2077: Johnny Silverhand Returns';
  const headline = 'WAKE UP SAMURAI';

  console.log(`📝 Concept: ${conceptTitle}`);
  console.log(`📝 Prompt (${johnnyPrompt.split(/\s+/).length} tokens): ${johnnyPrompt}\n`);

  const t0 = performance.now();
  const storageRoot = join(OUTPUT_DIR, 'step2-johnny-storage');
  mkdirSync(storageRoot, { recursive: true });

  const ingestion = new AssetIngestionService({ storageRoot });
  const engine = new SharpSvgCompositionEngine(ingestion, adapter);
  const gate = new QualityGateService(engine);
  const conceptEngine = new ConceptDrivenEngine(ingestion, engine, gate, {
    providers: [mockProvider()],
    imageAdapter: adapter,
  });

  let report: Step2Report = {
    concept: conceptTitle,
    theme: 'Cyberpunk 2077',
    prompt: johnnyPrompt,
    model: 'stabilityai/sdxl-turbo',
    device: 'cuda',
    generationTimeSec: 0,
    pngPath: '',
    sizeKB: 0,
    provenance: '',
    visualGatePassed: false,
    visualGateDiagnostics: [],
    clipScore: 0,
    clipMargin: 0,
    clipPassed: false,
    clipRationale: '',
    qualityScore: 0,
    qualityPassed: false,
    qualityFindings: [],
    overallVerdict: 'failed',
  };

  try {
    // Generate via ConceptDrivenEngine for full pipeline validation
    console.log('🔄 Generating concept via ConceptDrivenEngine...');
    const { proposals, enginesUsed } = await conceptEngine.generateConceptLab({
      title: conceptTitle,
      headline,
      prompt: johnnyPrompt,
      scriptText: 'A história completa de Johnny Silverhand, o rebelde icônico de Night City.',
      width: 1280,
      height: 720,
      genre: 'games',
    });

    const proposal = proposals[0];
    if (!proposal) {
      throw new Error('No proposals generated by ConceptDrivenEngine');
    }

    console.log(`📋 Engines used: ${enginesUsed.join(', ')}`);
    console.log(`📋 Concept archetype: ${proposal.concept.archetype}`);
    console.log(`📋 Acquired media: ${proposal.acquiredMedia.map((m) => `${m.role}=${m.provenance}`).join(', ')}`);

    // Render final composite
    console.log('🎨 Rendering final composite...');
    const rendered = await engine.renderDocumentToBuffer(proposal.document, 'png');
    const outPath = join(OUTPUT_DIR, 'cyberpunk-2077-johnny-silverhand-step2.png');
    writeFileSync(outPath, rendered);
    report.pngPath = outPath;
    report.sizeKB = Math.round(rendered.length / 1024);
    report.provenance = proposal.acquiredMedia.map((m) => `${m.role}=${m.provenance}`).join(', ');

    console.log(`💾 Saved: ${outPath} (${report.sizeKB} KB)\n`);

    // 1. Visual Content Gate
    console.log('[VisualContentGate] Evaluating final render...');
    const tempAsset = await ingestion.ingestBuffer({
      buffer: rendered,
      kind: 'image',
      extension: 'png',
      originalName: 'johnny-silverhand-step2-final.png',
    });
    const absPath = ingestion.resolvePortablePath(tempAsset.relativePath);
    const visualVerdict = await evaluateVisualContent({
      asset: tempAsset,
      assetPath: absPath,
      queryOrPrompt: johnnyPrompt,
      conceptTitle,
      genre: 'games',
    });
    report.visualGatePassed = visualVerdict.passed;
    report.visualGateDiagnostics = visualVerdict.diagnostics;
    console.log(`[VisualContentGate] ${visualVerdict.passed ? '✅ PASSED' : '❌ BLOCKED'}`);
    for (const d of visualVerdict.diagnostics) console.log(`  → ${d}`);
    if (visualVerdict.blockReason) console.log(`  ⛔ ${visualVerdict.blockReason}`);

    // 2. CLIP Semantic Evaluation
    console.log('\n[CLIP] Evaluating semantics...');
    try {
      const semResult = await adapter.evaluateImageSemantics!({
        imageBuffer: rendered,
        positiveConcepts: ['Johnny Silverhand', 'cyberpunk', 'chrome arm', 'neon city', 'game thumbnail'],
        negativeConcepts: ['placeholder', 'geometric shapes', 'gradient only', 'text only', 'blank', 'generic person'],
      });
      report.clipScore = Math.round(semResult.positiveScore * 100);
      report.clipMargin = semResult.margin;
      report.clipPassed = !semResult.isOffTopic && semResult.margin > 0.1;
      report.clipRationale = semResult.rationale;
      console.log(`[CLIP] Score=${report.clipScore}% margin=${semResult.margin.toFixed(3)} ${report.clipPassed ? '✅' : '❌'}`);
      console.log(`  → ${semResult.rationale}`);
    } catch (err) {
      report.clipRationale = `CLIP error: ${err instanceof Error ? err.message : String(err)}`;
      console.log(`[CLIP] ❌ ERROR: ${report.clipRationale}`);
    }

    // 3. Quality Gate
    console.log('\n[QualityGate] Evaluating structure...');
    const meta = await sharp(rendered).metadata();
    const stats = await sharp(rendered).stats();
    const w = meta.width ?? 0;
    const h = meta.height ?? 0;
    const meanStdev =
      ((stats.channels[0]?.stdev ?? 0) + (stats.channels[1]?.stdev ?? 0) + (stats.channels[2]?.stdev ?? 0)) / 3;

    const smallBuf = await sharp(rendered).resize(224, 126, { fit: 'fill' }).raw().toBuffer();
    let smallSum = 0;
    let smallCount = 0;
    for (let i = 0; i < smallBuf.length; i += 4) {
      smallSum += smallBuf[i] ?? 0;
      smallCount++;
    }
    const smallMean = smallCount > 0 ? smallSum / smallCount : 0;

    const edgeBuf = await sharp(rendered).greyscale().sharpen({ sigma: 1 }).raw().toBuffer();
    let edgeSum = 0;
    let edgeCount = 0;
    for (let i = 0; i < edgeBuf.length; i++) {
      edgeSum += edgeBuf[i] ?? 0;
      edgeCount++;
    }
    const avgEdge = edgeCount > 0 ? edgeSum / edgeCount : 0;

    const complexityScore = Math.min(100, Math.round(meanStdev * 2.5));

    // Legibility: measure LOCAL contrast in the text region (bottom 40% of image)
    // instead of global mean luminance which is misleading with dark overlays
    const textRegionH = Math.round(h * 0.4);
    const textRegionY = h - textRegionH;
    const textRegionBuf = await sharp(rendered)
      .extract({ left: 0, top: textRegionY, width: w, height: textRegionH })
      .resize(224, Math.round(224 * textRegionH / w), { fit: 'fill' })
      .raw()
      .toBuffer();
    let textLumMin = 255;
    let textLumMax = 0;
    for (let i = 0; i < textRegionBuf.length; i += 4) {
      const lum = (textRegionBuf[i] ?? 0) * 0.299 + (textRegionBuf[i + 1] ?? 0) * 0.587 + (textRegionBuf[i + 2] ?? 0) * 0.114;
      textLumMin = Math.min(textLumMin, lum);
      textLumMax = Math.max(textLumMax, lum);
    }
    const textContrast = textLumMax - textLumMin;
    // High contrast in text region = good legibility (white text on dark overlay)
    const legibilityScore = Math.min(100, Math.round(textContrast * 0.55 + 15));

    // Composition: combine edge density with structural diversity
    // Reduce edge weight since editorial overlays intentionally reduce global edges
    const compositionScore = Math.min(100, Math.round(avgEdge * 1.2 + meanStdev * 0.8));

    const overall = Math.round(complexityScore * 0.30 + legibilityScore * 0.40 + compositionScore * 0.30);
    const qualityPassed = overall >= 55 && meanStdev >= 18;

    report.qualityScore = overall;
    report.qualityPassed = qualityPassed;
    report.qualityFindings = [
      `Complexity: ${complexityScore}/100 (stdev=${meanStdev.toFixed(1)})`,
      `Legibility@textRegion: ${legibilityScore}/100 (contrast=${textContrast.toFixed(0)})`,
      `Composition: ${compositionScore}/100 (edgeAvg=${avgEdge.toFixed(1)}, stdev=${meanStdev.toFixed(1)})`,
      `Dimensions: ${w}×${h}`,
    ];
    if (!qualityPassed) report.qualityFindings.push(`⛔ Below threshold (overall=${overall})`);

    console.log(`[QualityGate] Score=${overall}/100 ${qualityPassed ? '✅ PASSED' : '❌ FAILED'}`);
    for (const f of report.qualityFindings) console.log(`  → ${f}`);

    // Overall verdict
    if (report.visualGatePassed && report.clipPassed && report.qualityPassed) {
      report.overallVerdict = 'approved';
    } else {
      report.overallVerdict = 'rejected';
    }

    const elapsed = ((performance.now() - t0) / 1000).toFixed(2);
    report.generationTimeSec = parseFloat(elapsed);

    console.log(`\n📋 OVERALL VERDICT: ${report.overallVerdict.toUpperCase()}`);
    console.log(`⏱️  Total time: ${elapsed}s`);
  } catch (err) {
    const elapsed = ((performance.now() - t0) / 1000).toFixed(2);
    report.generationTimeSec = parseFloat(elapsed);
    report.failureReason = err instanceof Error ? err.message : String(err);
    console.error(`\n❌ FAILED after ${elapsed}s: ${report.failureReason}`);
  } finally {
    // Gracefully shut down persistent worker to free GPU memory
    console.log('\n🔌 Shutting down persistent worker...');
    await adapter.shutdown();
  }

  // Write report
  const reportPath = join(OUTPUT_DIR, 'cs9-step2-johnny-report.html');
  writeFileSync(reportPath, generateStep2Report(report), 'utf-8');
  const summaryPath = join(OUTPUT_DIR, 'cs9-step2-johnny-summary.txt');
  writeFileSync(summaryPath, formatSummary(report), 'utf-8');

  console.log('\n' + '='.repeat(60));
  console.log(`📄 HTML Report: ${reportPath}`);
  console.log(`📝 Summary: ${summaryPath}`);
  console.log('='.repeat(60));
}

function formatSummary(r: Step2Report): string {
  return [
    `VERDICT: ${r.overallVerdict.toUpperCase()}`,
    `Concept: ${r.concept}`,
    `Prompt: ${r.prompt}`,
    `Model: ${r.model} | Device: ${r.device}`,
    `Time: ${r.generationTimeSec}s`,
    `PNG: ${r.pngPath || 'NONE'} (${r.sizeKB} KB)`,
    `Provenance: ${r.provenance || 'none'}`,
    `Visual Gate: ${r.visualGatePassed ? 'PASSED' : 'BLOCKED'} — ${r.visualGateDiagnostics.join('; ')}`,
    `CLIP: ${r.clipScore}% margin=${r.clipMargin.toFixed(3)} ${r.clipPassed ? 'PASSED' : 'FAILED'} — ${r.clipRationale}`,
    `Quality: ${r.qualityScore}/100 ${r.qualityPassed ? 'PASSED' : 'FAILED'} — ${r.qualityFindings.join('; ')}`,
    r.failureReason ? `FAILURE: ${r.failureReason}` : '',
  ].filter(Boolean).join('\n');
}

