// Embeds the OFL brand fonts as base64 so the identity pieces render the same in the preview, the PNG and the saved SVG,
// in the renderer and in the main process alike (no bundler or file path involved).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'packages/shared/assets/brand-fonts';
const fonts = {
  inter: { family: 'NB Inter', weight: 900, file: 'inter-latin-900-normal.woff2' },
  'inter-semibold': { family: 'NB Inter', weight: 600, file: 'inter-latin-600-normal.woff2' },
  anton: { family: 'NB Anton', weight: 400, file: 'anton-latin-400-normal.woff2' },
  'archivo-black': { family: 'NB Archivo Black', weight: 400, file: 'archivo-black-latin-400-normal.woff2' },
  bebas: { family: 'NB Bebas Neue', weight: 400, file: 'bebas-neue-latin-400-normal.woff2' },
  serif: { family: 'NB Instrument Serif', weight: 400, file: 'instrument-serif-latin-400-normal.woff2' },
  grotesk: { family: 'NB Space Grotesk', weight: 700, file: 'space-grotesk-latin-700-normal.woff2' },
  fredoka: { family: 'NB Fredoka', weight: 700, file: 'fredoka-latin-700-normal.woff2' },
  mono: { family: 'NB JetBrains Mono', weight: 700, file: 'jetbrains-mono-latin-700-normal.woff2' },
};
const lines = Object.entries(fonts).map(([id, font]) => `  '${id}': { family: '${font.family}', weight: ${font.weight}, base64: '${readFileSync(join(dir, font.file)).toString('base64')}' },`);
writeFileSync('packages/shared/src/brand-fonts.generated.ts', `// Generated by scripts/generate-brand-fonts.mjs from packages/shared/assets/brand-fonts (SIL OFL 1.1). Do not edit.\nexport const BRAND_FONT_FILES = {\n${lines.join('\n')}\n} as const;\nexport type BrandFontFileId = keyof typeof BRAND_FONT_FILES;\n`);
console.log('brand fonts: packages/shared/src/brand-fonts.generated.ts');
